"""Write docs/reference/cli.md from the argparse definitions of qdw (run after changing the CLI).

    PYTHONPATH=src python tools/gen_cli_docs.py
"""
import argparse
from pathlib import Path

from qd_workflows import cli


def _root() -> argparse.ArgumentParser:
    captured = {}

    def grab(self, *a, **k):
        captured["p"] = self
        raise SystemExit

    orig, argparse.ArgumentParser.parse_args = argparse.ArgumentParser.parse_args, grab
    try:
        cli.main([])
    except SystemExit:
        pass
    finally:
        argparse.ArgumentParser.parse_args = orig
    return captured["p"]


def _subs(p):
    return next((a for a in p._actions if isinstance(a, argparse._SubParsersAction)), None)


def _help(sp, name) -> str:
    h = next((c.help for c in sp._choices_actions if c.dest == name), "") or ""
    return h[0].upper() + h[1:] if h else ""


def _table(p) -> list:
    rows = [(", ".join(x.option_strings) or x.dest, " ".join((x.help or "").split()).replace("|", "\\|"), x.default)
            for x in p._actions if not isinstance(x, (argparse._HelpAction, argparse._SubParsersAction))]
    if not rows:
        return []
    fmt = lambda d: "" if d is None or d is False or d == argparse.SUPPRESS else f"`{d}`"
    return ["| Argument | Meaning | Default |", "|---|---|---|"] + [f"| `{a}` | {b} | {fmt(c)} |" for a, b, c in rows] + [""]


def _usage(p) -> list:
    return ["```text", p.format_usage().replace("usage: ", "").strip(), "```", ""]


def main() -> None:
    out = ["# Command line", "",
           "Every command is `qdw <group> <action>`; `--help` on any of them prints the same information. "
           "This page is generated by `tools/gen_cli_docs.py`.", ""]
    g = _subs(_root())
    for gname, gp in g.choices.items():
        out += [f"## qdw {gname}", "", _help(g, gname) + ".", ""]
        acts = _subs(gp)
        if not acts:
            out += _usage(gp) + _table(gp)
            continue
        for aname, ap in acts.choices.items():
            out += [f"### qdw {gname} {aname}", "", _help(acts, aname) + ".", ""]
            inner = _subs(ap)
            if inner:
                for iname, ip in inner.choices.items():
                    out += [f"**`qdw {gname} {aname} {iname}`**: {_help(inner, iname)}.", ""] + _usage(ip) + _table(ip)
            else:
                out += _usage(ap) + _table(ap)
    Path(__file__).resolve().parents[1].joinpath("docs/reference/cli.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
